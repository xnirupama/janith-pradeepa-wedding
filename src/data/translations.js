export function applyInvitationCopy(invitation, copy) {
  const { locationDescription, weekday, month, scheduleTitles, arrivalTitle, arrivalText, ...narrative } = copy;
  return {
    ...invitation,
    ...narrative,
    dateParts: { ...invitation.dateParts, weekday, month },
    ...(invitation.schedule ? { schedule: invitation.schedule.map((item, index) => ({ ...item, title: scheduleTitles?.[index] || item.title })) } : {}),
    ...(invitation.arrival ? { arrival: { ...invitation.arrival, title: arrivalTitle, text: arrivalText } } : {}),
    location: { ...invitation.location, description: locationDescription },
  };
}

export function localizeInvitation(invitation, language) {
  if (language !== "si") return invitation;
  const copy = sinhalaInvitationCopy[invitation.slug];
  if (!copy) return invitation;
  return applyInvitationCopy(invitation, copy);
}
